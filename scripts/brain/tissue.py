"""Tissue measurements for every /brain region.

Uses the same label volume as cerebra_meshes.py (CerebrA plus the derived white matter) on the
MNI-ICBM152 2009c symmetric template, and that template's own tissue maps (Fonov et al. 2011,
NeuroImage 54:313, doi:10.1016/j.neuroimage.2010.07.033; free use with copyright notice):

  - volume: voxel count (1 mm^3 voxels) -> cm^3, in the template's average-brain space
  - gm/wm/csf: mean grey matter / white matter / cerebrospinal fluid probability inside the label
  - myelin (cortical labels only): median T1w/T2w ratio over the label's grey-matter voxels (gm > 0.5),
    divided by the median over all cortical labels. T1w/T2w is the standard MRI proxy for
    intracortical myelin (Glasser & Van Essen 2011, J Neurosci 31:11597,
    doi:10.1523/JNEUROSCI.2180-11.2011); on an average template it is blurred, so it is shown only
    relative to the rest of the cortex.

The template and CerebrA's cortical labels are left-right mirror images, so there are no real
hemisphere differences to report: each region is written once, both hemispheres combined.

Usage: python -P scripts/brain/tissue.py   (downloads the 2009c NIfTI zip, ~60 MB, into scripts/.cache/mni/)
Writes src/app/brain/data/tissue.ts.
"""

import json
import sys
import urllib.request
import zipfile
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import cerebra_meshes as cm  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
CACHE = ROOT / 'scripts' / '.cache' / 'mni'
ZIP_URL = 'http://www.bic.mni.mcgill.ca/~vfonov/icbm/2009/mni_icbm152_nlin_sym_09c_nifti.zip'
MAPS = CACHE / 'mni_icbm152_nlin_sym_09c'
OUT = ROOT / 'src' / 'app' / 'brain' / 'data' / 'tissue.ts'


def fetch():
    if MAPS.exists():
        return
    CACHE.mkdir(parents=True, exist_ok=True)
    path = CACHE / 'mni_icbm152_nlin_sym_09c_nifti.zip'
    if not path.exists():
        print('downloading', ZIP_URL)
        urllib.request.urlretrieve(ZIP_URL, path)
    zipfile.ZipFile(path).extractall(CACHE)


def main():
    fetch()
    full, _, jobs = cm.label_volume()
    load = lambda name: cm.read_nifti(MAPS / f'mni_icbm152_{name}_tal_nlin_sym_09c.nii', as_float=True)[0]
    gm, wm, csf, t1, t2 = (load(n) for n in ('gm', 'wm', 'csf', 't1', 't2'))
    assert gm.shape == full.shape, 'tissue maps are not on the CerebrA grid'
    ratio = t1 / np.maximum(t2, 1e-3)

    out, cortical = {}, {}
    for key, side, mb, name, cid in jobs:
        m = full == cid
        if not m.any():
            continue
        p = np.array([gm[m].mean(), wm[m].mean(), csf[m].mean()])
        p = p / p.sum()
        out[key] = {'volume': round(int(m.sum()) / 1000, 2), 'gm': round(float(p[0]), 3),
                    'wm': round(float(p[1]), 3), 'csf': round(float(p[2]), 3)}
        if mb >= 1000:  # Mindboggle cortical label ids
            cortical[key] = float(np.median(ratio[m & (gm > 0.5)]))
    ref = float(np.median(list(cortical.values())))
    for key, r in cortical.items():
        out[key]['myelin'] = round(r / ref, 3)
    # Report each region for both hemispheres together: cortical labels are mirror images, and
    # midline structures (brainstem, vermis, 3rd/4th ventricles) are one structure split unevenly.
    regions = {}
    for key, v in out.items():
        r = regions.setdefault(key[2:], {'volume': 0.0, 'gm': 0.0, 'wm': 0.0, 'csf': 0.0, 'myelin': []})
        r['volume'] += v['volume']
        for t in ('gm', 'wm', 'csf'):
            r[t] += v[t] * v['volume']
        if 'myelin' in v:
            r['myelin'].append(v['myelin'])
    for name, r in regions.items():
        for t in ('gm', 'wm', 'csf'):
            r[t] = round(r[t] / r['volume'], 3)
        r['volume'] = round(r['volume'], 2)
        myelin = r.pop('myelin')
        if myelin:
            r['myelin'] = round(sum(myelin) / len(myelin), 3)
        print(f"{name:36s} {r['volume']:7.2f} cm3  gm {r['gm']:.2f} wm {r['wm']:.2f} csf {r['csf']:.2f}  myelin {r.get('myelin', '')}")

    header = (
        '// Generated by scripts/brain/tissue.py -- regenerate, don\'t hand-edit.\n'
        '// Per region (one side; the template is symmetric, so both sides are equal), measured on the MNI-ICBM152 2009c template the CerebrA\n'
        '// labels are drawn on: volume in cm^3, mean grey/white/CSF probability from the template\'s\n'
        '// tissue maps, and for cortex a T1w/T2w myelin index relative to the cortical median.\n\n'
    )
    body = (
        'export interface Tissue {\n'
        '  volume: number;\n'
        '  gm: number;\n'
        '  wm: number;\n'
        '  csf: number;\n'
        '  myelin?: number;\n'
        '}\n\n'
        'export const TISSUE: Record<string, Tissue> = {\n'
        + ''.join(f'  {json.dumps(k)}: {json.dumps(v, separators=(",", ":"))},\n' for k, v in sorted(regions.items()))
        + '};\n'
    )
    OUT.write_text(header + body, encoding='utf-8')
    print('wrote', OUT.relative_to(ROOT), len(regions), 'regions')


if __name__ == '__main__':
    main()
