"""Build ../data/spacecraft.ts: trajectories of the five probes leaving the Solar System, plus
the heliosphere boundary crossings measured by the two Voyagers.

Trajectories: JPL Horizons heliocentric ecliptic J2000 positions (raw responses cached under
spacecraft/), sampled every 10 days through 2000 (the planetary-flyby era, where paths bend
sharply) and every 60 days after, up to each ephemeris's end (2050 for Pioneer 10/11 and
New Horizons).

Heliosphere crossings: dates from the saved Wikipedia articles (../wikipedia/Heliosphere/:
Voyager 1 timeline — termination shock 2004-12-17 "at 94 AU", heliopause 2012-08-25 "at
121 AU"; Voyager 2 — termination shock "August 30, 2007", heliopause 2018-11-05). The
position at each crossing comes from Horizons, so the boundaries are anchored where the
spacecraft actually measured them.

Run:  python -I generateSpacecraft.py
"""
import json
import os
import re
import urllib.parse
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
CACHE = os.path.join(HERE, 'spacecraft')
OUT = os.path.join(HERE, '..', 'data', 'spacecraft.ts')

# name -> (Horizons ID, first date, last date)
PROBES = {
    'Pioneer 10': ('-23', '1972-03-04', '2049-12-31'),
    'Pioneer 11': ('-24', '1973-04-07', '2049-12-31'),
    'Voyager 2': ('-32', '1977-08-21', '2049-12-31'),
    'Voyager 1': ('-31', '1977-09-06', '2049-12-31'),
    'New Horizons': ('-98', '2006-01-20', '2049-12-31'),
}
CROSSINGS = [
    ('Voyager 1', 'terminationShock', '2004-12-17'),
    ('Voyager 1', 'heliopause', '2012-08-25'),
    ('Voyager 2', 'terminationShock', '2007-08-30'),
    ('Voyager 2', 'heliopause', '2018-11-05'),
]


def horizons_vectors(sid, start, stop, step, tag):
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, f'{tag}.txt')
    if not os.path.exists(path):
        q = {'format': 'text', 'COMMAND': f"'{sid}'", 'CENTER': "'500@10'", 'EPHEM_TYPE': "'VECTORS'",
             'REF_PLANE': "'ECLIPTIC'", 'REF_SYSTEM': "'ICRF'", 'START_TIME': f"'{start}'", 'STOP_TIME': f"'{stop}'",
             'STEP_SIZE': f"'{step}'", 'VEC_TABLE': "'1'", 'OUT_UNITS': "'AU-D'", 'CSV_FORMAT': "'YES'"}
        url = 'https://ssd.jpl.nasa.gov/api/horizons.api?' + urllib.parse.urlencode(q)
        open(path, 'w', encoding='utf-8', newline='\n').write(urllib.request.urlopen(url, timeout=120).read().decode('utf-8'))
    text = open(path, encoding='utf-8').read()
    block = text[text.index('$$SOE') + 5:text.index('$$EOE')]
    rows = []
    for line in block.strip().splitlines():
        parts = [p.strip() for p in line.split(',')]
        jd, x, y, z = float(parts[0]), float(parts[2]), float(parts[3]), float(parts[4])
        rows.append([round(jd, 1), round(x, 4), round(y, 4), round(z, 4)])
    return rows


def main():
    probes = {}
    for name, (sid, start, stop) in PROBES.items():
        tag = re.sub(r'\W+', '_', name)
        early_end = min(stop, '2000-01-01')
        pts = horizons_vectors(sid, start, early_end, '10d', f'{tag}_early') if start < '2000-01-01' else []
        late_start = '2000-01-11' if start < '2000-01-01' else start
        pts += horizons_vectors(sid, late_start, stop, '60d', f'{tag}_late')
        probes[name] = pts
        r_end = sum(c * c for c in pts[-1][1:]) ** 0.5
        print(f'{name:13s} {len(pts)} points, {r_end:.1f} AU at end')

    crossings = []
    for name, kind, date in CROSSINGS:
        sid = PROBES[name][0]
        tag = re.sub(r'\W+', '_', f'{name}_{kind}')
        x, y, z = horizons_vectors(sid, date, f'{date} 00:01', '1', tag)[0][1:]
        r = (x * x + y * y + z * z) ** 0.5
        crossings.append({'probe': name, 'kind': kind, 'date': date, 'position': [x, y, z], 'distanceAU': round(r, 2)})
        print(f'{name} {kind} {date}: {r:.1f} AU')

    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('''// GENERATED by solarsystem/jpl/generateSpacecraft.py — do not hand-edit; regenerate instead.
//
// Heliocentric ecliptic J2000 trajectories (AU) of the probes leaving the Solar System, from
// JPL Horizons (cached under solarsystem/jpl/spacecraft/), as [JD, x, y, z] rows — 10-day
// steps before 2000, 60-day after. heliosphereCrossings: where the Voyagers actually crossed
// the termination shock / heliopause (dates from their Wikipedia articles, positions from
// Horizons); components/Heliosphere.tsx anchors its boundaries to these.

export type TrajectoryRow = [number, number, number, number];

export type HeliosphereCrossing = {
  probe: string;
  kind: 'terminationShock' | 'heliopause';
  date: string;
  position: [number, number, number]; // AU, ecliptic J2000
  distanceAU: number;
};

export const heliosphereCrossings: HeliosphereCrossing[] = ''' + json.dumps(crossings, indent=2) + ''';

export const spacecraftTrajectories: Record<string, TrajectoryRow[]> = {
''')
        for name, pts in probes.items():
            f.write(f'  {json.dumps(name)}: {json.dumps(pts, separators=(",", ":"))},\n')
        f.write('};\n')
    print(f'wrote {OUT} ({os.path.getsize(OUT) // 1024} KB)')


if __name__ == '__main__':
    main()
