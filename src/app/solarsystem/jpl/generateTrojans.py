"""Build ../data/trojans.ts from JPL Small-Body Database queries saved under trojans/.

Sources (JPL SBDB Query API, https://ssd-api.jpl.nasa.gov/sbdb_query.api, saved raw):
  trojans/jupiter_trojans_sbdb.json   sb-class=TJN (every catalogued Jupiter Trojan)
  trojans/neptune_coorbital_sbdb.json  every small body with 29.7 < a < 30.5 AU

Both queries ask for fields spkid, full_name, epoch, e, a, i, om, w, ma, H, diameter
(osculating heliocentric ecliptic J2000 elements at each object's own epoch).

Jupiter: kept to H <= 14 (roughly > 10 km; ~4,600 of ~16,400), a near-complete census at
that size that keeps the data file small. Neptune: SBDB has no Trojan class, and the a-window
also catches comets / scattered objects that merely share Neptune's semimajor axis, so an
object is kept only if it's actually co-orbiting at a Lagrange point — e < 0.2 and a mean
longitude 25-115 deg ahead of (L4) or behind (L5) Neptune's at the object's epoch.

The same L4/L5 test labels every Jupiter Trojan's camp (L4 "Greeks", L5 "Trojans"); mean
longitudes for Jupiter and Neptune come from JPL's "Approximate Positions of the Planets"
(Standish, Table 1, valid 1800-2050).

Re-fetch (overwrites the cache):
  curl -G https://ssd-api.jpl.nasa.gov/sbdb_query.api --data-urlencode "fields=spkid,full_name,epoch,e,a,i,om,w,ma,H,diameter" --data-urlencode "sb-class=TJN" -o trojans/jupiter_trojans_sbdb.json
  curl -G https://ssd-api.jpl.nasa.gov/sbdb_query.api --data-urlencode "fields=spkid,full_name,epoch,e,a,i,om,w,ma,H,diameter" --data-urlencode 'sb-cdata={"AND":["a|RG|29.7|30.5"]}' -o trojans/neptune_coorbital_sbdb.json

Run:  python -I generateTrojans.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'data', 'trojans.ts')
JUPITER_H_LIMIT = 14.0

# Standish Table 1: mean longitude L = L0 + rate * T (deg, T = Julian centuries from J2000)
PLANET_MEAN_LONGITUDE = {
    'Jupiter': (34.39644051, 3034.74612775),
    'Neptune': (-55.12002969, 218.45945325),
}


def load(name):
    d = json.load(open(os.path.join(HERE, 'trojans', name), encoding='utf-8'))
    return [dict(zip(d['fields'], row)) for row in d['data']]


def camp(row, planet):
    """4 or 5 for an L4/L5 co-orbital, else None."""
    L0, rate = PLANET_MEAN_LONGITUDE[planet]
    T = (float(row['epoch']) - 2451545.0) / 36525
    planet_lambda = L0 + rate * T
    obj_lambda = float(row['om']) + float(row['w']) + float(row['ma'])
    d = (obj_lambda - planet_lambda + 180) % 360 - 180
    if 25 <= d <= 115:
        return 4
    if -115 <= d <= -25:
        return 5
    return None


def compact(row, c):
    return [
        round(float(row['a']), 5), round(float(row['e']), 5), round(float(row['i']), 4),
        round(float(row['om']), 4), round(float(row['w']), 4), round(float(row['ma']), 4),
        float(row['epoch']), c,
    ]


def main():
    jupiter, unclassified = [], 0
    for r in load('jupiter_trojans_sbdb.json'):
        if not r['H'] or float(r['H']) > JUPITER_H_LIMIT:
            continue
        c = camp(r, 'Jupiter')
        if c is None:
            unclassified += 1
            continue
        jupiter.append(compact(r, c))

    neptune, neptune_names = [], []
    for r in load('neptune_coorbital_sbdb.json'):
        if float(r['e']) >= 0.2:
            continue
        c = camp(r, 'Neptune')
        if c is None:
            continue
        neptune.append(compact(r, c))
        neptune_names.append(r['full_name'].strip())

    l4 = sum(1 for t in jupiter if t[7] == 4)
    print(f'Jupiter: {len(jupiter)} kept (L4 {l4}, L5 {len(jupiter) - l4}), {unclassified} outside L4/L5 window dropped')
    print(f'Neptune: {len(neptune)} kept: ' + ', '.join(neptune_names))

    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('''// GENERATED by solarsystem/jpl/generateTrojans.py — do not hand-edit; regenerate instead.
//
// Jupiter and Neptune Trojans from the JPL Small-Body Database (raw query results saved
// under solarsystem/jpl/trojans/). Jupiter: every catalogued Trojan with H <= 14 (roughly
// > 10 km). Neptune: SBDB co-orbitals filtered to real L4/L5 Trojans (see the generator).
// Each row is osculating heliocentric ecliptic J2000 elements at the object's own epoch:
//   [a (AU), e, i (deg), node (deg), arg. perihelion (deg), mean anomaly (deg), epoch (JD TDB), camp (4 | 5)]
// They're propagated to the simulation date (components/Trojans.tsx), so the two clouds sit
// where they really are, ~60 deg ahead of (L4) and behind (L5) their planet.

export type TrojanRow = [number, number, number, number, number, number, number, 4 | 5];

''')
        f.write(f'// {len(neptune)} objects: ' + ', '.join(neptune_names) + '\n')
        f.write('export const neptuneTrojans: TrojanRow[] = ' + json.dumps(neptune, separators=(',', ':')) + ';\n\n')
        f.write('export const jupiterTrojans: TrojanRow[] = [\n')
        for t in jupiter:
            f.write('  ' + json.dumps(t, separators=(',', ':')) + ',\n')
        f.write('];\n')
    print(f'wrote {OUT} ({os.path.getsize(OUT) // 1024} KB)')


if __name__ == '__main__':
    main()
