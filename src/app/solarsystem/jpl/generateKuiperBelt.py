"""Build ../data/kuiperBelt.ts from the JPL SBDB trans-Neptunian census (tno/tno_sbdb.json).

Source: https://ssd-api.jpl.nasa.gov/sbdb_query.api?fields=spkid,full_name,epoch,e,a,i,om,w,ma,H&sb-class=TNO
(saved raw). Kept: H <= 8 (very roughly > 100 km; ~5,000 of ~7,700), osculating heliocentric
ecliptic J2000 elements at each object's epoch. Population split by semimajor axis:
  0 = Kuiper belt (a < 50 AU: classical + resonant objects, incl. plutinos at 39.4 AU)
  1 = scattered disc / detached (a >= 50 AU)

Run:  python -I generateKuiperBelt.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'data', 'kuiperBelt.ts')
H_LIMIT = 8.0


def main():
    d = json.load(open(os.path.join(HERE, 'tno', 'tno_sbdb.json'), encoding='utf-8'))
    rows = [dict(zip(d['fields'], r)) for r in d['data']]
    out = []
    for r in rows:
        if not r['H'] or float(r['H']) > H_LIMIT or float(r['e']) >= 1:
            continue
        a = float(r['a'])
        out.append([round(a, 4), round(float(r['e']), 4), round(float(r['i']), 3), round(float(r['om']), 3),
                    round(float(r['w']), 3), round(float(r['ma']), 3), float(r['epoch']), 0 if a < 50 else 1])
    kb = sum(1 for o in out if o[7] == 0)
    print(f'{len(out)} kept: Kuiper belt {kb}, scattered/detached {len(out) - kb}')
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('''// GENERATED by solarsystem/jpl/generateKuiperBelt.py — do not hand-edit; regenerate instead.
//
// Trans-Neptunian objects with H <= 8 from the JPL Small-Body Database (raw query saved under
// solarsystem/jpl/tno/). Rows: [a (AU), e, i, node, arg. perihelion, mean anomaly (deg),
// epoch (JD TDB), population (0 = Kuiper belt a < 50 AU, 1 = scattered disc / detached)].
// Propagated to the simulation date, so plutinos really avoid Neptune and the belt's real
// clumping shows (components/KuiperBelt.tsx).

export type TnoRow = [number, number, number, number, number, number, number, 0 | 1];

export const kuiperBelt: TnoRow[] = [
''')
        for o in out:
            f.write('  ' + json.dumps(o, separators=(',', ':')) + ',\n')
        f.write('];\n')
    print(f'wrote {OUT} ({os.path.getsize(OUT) // 1024} KB)')


if __name__ == '__main__':
    main()
